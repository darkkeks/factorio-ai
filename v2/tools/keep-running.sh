#!/bin/bash
# «Не ставить паузу»: игра идёт всегда — и без людей, и без занятых ботов (обычно она встаёт на паузу сама).
#   keep-running.sh on | off | status
# Файл-признак читает сторож паузы (~/robot/bin/pause-guard.py) раз в 5 секунд. С режимом ожидания (hold.sh) совместимо:
# боты не играют, а мир живёт сам. Игра без присмотра меняет карту: завод работает, враги нападают.
FLAG=${KEEP_FILE:-$HOME/robot/keep-running}
case "$1" in
  on) date '+%F %T' > "$FLAG"; echo "пауза запрещена: игра идёт всегда ($FLAG)";;
  off) rm -f "$FLAG"; echo "обычное правило паузы: игра идёт, пока в ней есть люди или занятые боты";;
  status) [ -f "$FLAG" ] && echo "пауза запрещена с $(cat "$FLAG")" || echo "обычное правило паузы";;
  *) sed -n 2,5p "$0"; exit 1;;
esac
